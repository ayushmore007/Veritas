"""Load the trained flow detector and score flows or PCAPs with per-flow explanations.

This is the one place the API (and anything else that serves the model) goes through, so every
caller gets the same guarantees:

* the **same feature view as training** — identity fields are dropped, columns are re-ordered to the
  model's saved order, missing ones become 0 and are *reported*, never silently invented;
* the **saved decision threshold**, not a hard-coded 0.5;
* **bounded** work — row and file-size limits are enforced here, not left to the web layer.
"""

from __future__ import annotations

import importlib.metadata
import json
import os
import tempfile
import warnings
from pathlib import Path
from typing import Any

import numpy as np

from veritas.baselines.model import BaselineClassifier
from veritas.features import behavioural_features
from veritas.testbed.config import project_root

MAX_ROWS = 5000
MAX_PCAP_BYTES = 50 * 1024 * 1024


class ModelNotAvailable(RuntimeError):
    """No trained model on disk. The message says how to build one."""


class InputError(ValueError):
    """The caller sent something the model cannot score (maps to HTTP 4xx)."""


def default_model_dir() -> Path:
    override = os.environ.get("VERITAS_MODEL_DIR")
    return Path(override) if override else project_root() / "models" / "flow-detector"


class FlowDetector:
    """A trained classifier plus its saved threshold, card and a cached SHAP explainer."""

    def __init__(self, model: BaselineClassifier, directory: Path, summary: dict[str, Any]) -> None:
        self.model = model
        self.directory = directory
        self.summary = summary
        self.threshold = float(model.metadata.get("threshold", 0.5))
        self._explainer: Any = None

    # -- construction -------------------------------------------------------------------------

    @classmethod
    def load(cls, directory: Path | None = None) -> FlowDetector:
        directory = Path(directory) if directory else default_model_dir()
        path = directory / "model.joblib"
        if not path.is_file():
            raise ModelNotAvailable(
                f"No trained model at {path}. Build a corpus and run `veritas-train fit` "
                "(see docs/TRAINING.md)."
            )
        with warnings.catch_warnings():
            # An sklearn version mismatch warns on unpickle; surface it via info() instead.
            warnings.simplefilter("ignore")
            model = BaselineClassifier.load(path)
        metrics_path = directory / "metrics.json"
        summary = json.loads(metrics_path.read_text(encoding="utf-8")) if metrics_path.is_file() else {}
        return cls(model, directory, summary)

    # -- introspection ------------------------------------------------------------------------

    def info(self) -> dict[str, Any]:
        import sklearn

        meta = self.model.metadata
        deployed = self.summary.get("deployed_profile")
        profile = (self.summary.get("profiles") or {}).get(deployed or "", {})
        evaluation = profile.get("evaluation", {})
        trained_with = meta.get("sklearn_version")
        cfm_trained = meta.get("cicflowmeter_version")
        try:
            cfm_running = importlib.metadata.version("cicflowmeter")
        except importlib.metadata.PackageNotFoundError:
            cfm_running = None
        return {
            "version": meta.get("version"),
            "trained_at": meta.get("trained_at"),
            "profile": meta.get("profile"),
            "estimator": meta.get("estimator"),
            "threshold": self.threshold,
            "n_features": len(self.model.feature_cols),
            "features": list(self.model.feature_cols),
            "training_samples": meta.get("n_samples"),
            "class_counts": meta.get("class_counts"),
            "clean_test": evaluation.get("clean_test"),
            "held_out_variants": evaluation.get("held_out_variants"),
            "top_features": profile.get("top_features"),
            "sklearn_trained_with": trained_with,
            "sklearn_running": sklearn.__version__,
            "sklearn_mismatch": bool(trained_with and trained_with != sklearn.__version__),
            # Feature semantics (units, packet counting) have changed between cicflowmeter releases,
            # so a different version than the one that built the training corpus can shift inputs.
            "cicflowmeter_trained_with": cfm_trained,
            "cicflowmeter_running": cfm_running,
            "cicflowmeter_mismatch": bool(cfm_trained and cfm_running and cfm_trained != cfm_running),
            "limitations": (
                "Trained on synthetic lab traffic generated by this repository; not validated on "
                "production networks. See MODEL_CARD.md."
            ),
        }

    # -- scoring ------------------------------------------------------------------------------

    def _matrix(self, rows: list[dict[str, Any]]) -> tuple[np.ndarray, list[list[str]]]:
        cols = self.model.feature_cols
        x = np.zeros((len(rows), len(cols)))
        missing: list[list[str]] = []
        for i, raw in enumerate(rows):
            feats = behavioural_features(raw)
            gone = []
            for j, col in enumerate(cols):
                value = feats.get(col)
                if isinstance(value, bool) or not isinstance(value, (int, float)) or not np.isfinite(value):
                    if value is None or col not in feats:
                        gone.append(col)
                    value = 0.0
                x[i, j] = float(value)
            missing.append(gone)
        return x, missing

    def _shap_values(self, x: np.ndarray) -> np.ndarray | None:
        try:
            import shap

            pipe = self.model.pipeline
            if self._explainer is None:
                self._explainer = shap.TreeExplainer(pipe.named_steps["clf"])
            values = self._explainer.shap_values(pipe.named_steps["scaler"].transform(x))
        except Exception:
            return None
        if isinstance(values, list):
            values = values[1] if len(values) > 1 else values[0]
        values = np.asarray(values)
        if values.ndim == 3:
            values = values[:, :, 1] if values.shape[2] > 1 else values[:, :, 0]
        return values

    def predict(
        self, rows: list[dict[str, Any]], *, explain: bool = True, top_k: int = 5
    ) -> list[dict[str, Any]]:
        if not rows:
            raise InputError("no flows supplied")
        if len(rows) > MAX_ROWS:
            raise InputError(f"too many flows: {len(rows)} (max {MAX_ROWS})")
        x, missing = self._matrix(rows)
        proba = self.model.predict_proba(x)
        mal = proba[:, 1] if proba.shape[1] > 1 else np.asarray(self.model.predict(x), dtype=float)
        shap_vals = self._shap_values(x) if explain else None

        out: list[dict[str, Any]] = []
        for i, raw in enumerate(rows):
            p = float(mal[i])
            item: dict[str, Any] = {
                "flow_id": str(raw.get("flow_id", i)),
                "verdict": "malicious" if p >= self.threshold else "benign",
                "malicious_probability": round(p, 4),
                "threshold": self.threshold,
                "missing_features": len(missing[i]),
            }
            if shap_vals is not None:
                order = np.argsort(np.abs(shap_vals[i]))[::-1][:top_k]
                item["top_features"] = [
                    {
                        "feature": self.model.feature_cols[j],
                        "value": round(float(x[i, j]), 6),
                        # Positive pushes toward malicious, negative toward benign.
                        "contribution": round(float(shap_vals[i, j]), 5),
                    }
                    for j in order
                ]
            if len(missing[i]) > len(self.model.feature_cols) // 2:
                item["warning"] = (
                    "More than half of the model's features were absent from this flow; the "
                    "verdict is unreliable. Supply CICFlowMeter-style features."
                )
            out.append(item)
        return out

    def analyze_pcap_bytes(self, data: bytes, *, ports: list[int] | None = None, explain: bool = True) -> dict[str, Any]:
        """Extract flows from raw PCAP bytes and score each one."""
        if len(data) > MAX_PCAP_BYTES:
            raise InputError(f"PCAP too large: {len(data)} bytes (max {MAX_PCAP_BYTES})")
        if not data:
            raise InputError("empty upload")
        fd, name = tempfile.mkstemp(suffix=".pcap")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            return self.analyze_pcap(Path(name), ports=ports, explain=explain)
        finally:
            Path(name).unlink(missing_ok=True)

    def analyze_pcap(self, pcap: Path, *, ports: list[int] | None = None, explain: bool = True) -> dict[str, Any]:
        from veritas.capture.cicflowmeter_extract import extract_flows_from_pcap
        from veritas.capture.entropy import ENTROPY_FIELDS, add_entropy_features

        try:
            flows = extract_flows_from_pcap(pcap, testbed_ports=ports)
        except ValueError as exc:
            raise InputError(f"not a readable PCAP: {exc}") from exc
        if not flows:
            return {"flows": [], "summary": {"flows": 0, "malicious": 0, "benign": 0},
                    "note": "No UDP/TCP flows found in this capture."}
        if any(c in self.model.feature_cols for c in ENTROPY_FIELDS):
            add_entropy_features(pcap, flows)
        verdicts = self.predict(flows[:MAX_ROWS], explain=explain)
        results = []
        for flow, verdict in zip(flows, verdicts, strict=False):
            results.append(
                {
                    **verdict,
                    "flow_id": f"{flow.get('src_ip')}:{flow.get('src_port')}->"
                    f"{flow.get('dst_ip')}:{flow.get('dst_port')}",
                    "src_ip": flow.get("src_ip"),
                    "dst_ip": flow.get("dst_ip"),
                    "src_port": flow.get("src_port"),
                    "dst_port": flow.get("dst_port"),
                    "protocol": flow.get("protocol"),
                    "duration_s": round(float(flow.get("flow_duration") or 0.0), 4),
                    "packets": int((flow.get("tot_fwd_pkts") or 0) + (flow.get("tot_bwd_pkts") or 0)),
                }
            )
        malicious = sum(1 for r in results if r["verdict"] == "malicious")
        return {
            "flows": results,
            "summary": {
                "flows": len(results),
                "malicious": malicious,
                "benign": len(results) - malicious,
                "truncated": len(flows) > MAX_ROWS,
            },
        }
