"""Render a human-readable model card from the training summary (metrics.json)."""

from __future__ import annotations

from typing import Any


def _r(block: dict[str, Any] | None) -> str:
    if not block or block.get("value") is None:
        return "n/a"
    ci = block.get("ci95")
    span = f" (95% CI {ci[0]:.2f}–{ci[1]:.2f})" if ci else ""
    return f"{block['value']:.3f}{span} [{block['hits']}/{block['total']}]"


def render_model_card(summary: dict[str, Any]) -> str:
    corpus, env = summary["corpus"], summary["environment"]
    deployed = summary["deployed_profile"]
    lines = [
        f"# Veritas flow detector — model card (v{summary['version']})",
        "",
        "**Task:** classify a single QUIC/UDP flow as `benign` or `malicious` from behavioural "
        "CICFlowMeter statistics (volume, direction, timing, burstiness) plus packet-shape entropy.",
        "",
        "**Intended use:** research and lab testbeds; a second opinion beside the LLM defender agent. "
        "**Not** validated for production networks (see Limitations).",
        "",
        f"**Deployed profile:** `{deployed}` · trained {summary['trained_at']} · "
        f"python {env['python']}, scikit-learn {env['sklearn']}",
        "",
        "## Data",
        "",
        f"- {corpus['flows']} flows from {corpus['captures']} captures "
        f"({corpus['benign']} benign / {corpus['malicious']} malicious, "
        f"{corpus['evaded_malicious']} evaded, {corpus['held_out_variant_flows']} in held-out variants)",
        f"- Split (by capture): {corpus['split_counts']}. {corpus['split_grouping']}",
        "- All traffic is **synthetic lab traffic** generated by this repository's testbed.",
        "- Admissible features only: identity fields (IPs, ports, clock) and label-bearing fields are "
        "excluded (`veritas/features.py`).",
        "",
        "## Method",
        "",
        "Grouped (by capture) stratified cross-validation over logistic regression, random forest, "
        "extra trees and gradient boosting; best deployable family by out-of-fold F1; decision "
        f"threshold from out-of-fold predictions at FPR ≤ {summary['config']['target_fpr']}. "
        "Held-out evasion variants are never trained on.",
        "",
    ]
    for name, rep in summary["profiles"].items():
        tag = " (deployed)" if name == deployed else ""
        sel, ev = rep["selected"], rep["evaluation"]
        pool = rep["training_pool"]
        lines += [
            f"## Profile `{name}`{tag}",
            "",
            f"- Selected: **{sel['family']}** `{sel['params']}` — CV F1 {sel['cv_f1']}, "
            f"CV FPR {sel['cv_fpr']}; threshold **{rep['threshold']}**",
            f"- Training pool: {pool['flows']} flows / {pool['captures']} captures "
            f"({pool['evaded_malicious']} evaded malicious)",
            "",
        ]
        ct = ev.get("clean_test")
        if ct:
            lines += [
                "**Clean held-out test split**",
                "",
                f"- Recall: {_r(ct['recall'])}",
                f"- False-positive rate: {_r(ct['false_positive_rate'])}",
                f"- Precision: {_r(ct['precision'])} · F1 {ct['f1']} · ROC-AUC {ct.get('roc_auc')}",
            ]
            for atk, blk in ct.get("recall_by_attack", {}).items():
                lines.append(f"- Recall, `{atk}`: {_r(blk)}")
            if ct.get("caveat"):
                lines.append(f"- ⚠ {ct['caveat']}")
            lines.append("")
        for title, key in (
            ("Evaded flows in the test split (attack success rate = missed share)", "evaded_test_by_strength"),
            ("All evaded flows, none seen in training", "evaded_all_unseen_by_strength"),
        ):
            block = ev.get(key)
            if block:
                lines += [f"**{title}**", ""]
                lines += [f"- strength {s}: ASR {_r(v['attack_success_rate'])}" for s, v in block.items()]
                lines.append("")
        held = ev.get("held_out_variants")
        if held:
            lines += ["**Held-out evasion variants (never trained on)**", ""]
            lines += [f"- `{v}`: ASR {_r(b['attack_success_rate'])}" for v, b in held.items()]
            lines.append("")
        loao = rep.get("leave_one_attack_out")
        if loao:
            lines += ["**Attack types the model never saw (train without X, test on X)**", ""]
            lines += [f"- `{a}`: recall {_r(v['recall_on_unseen_attack'])}" for a, v in loao.items()]
            lines.append("")
        if rep["top_features"]:
            lines += ["**Top features:** " + ", ".join(f"`{t['feature']}`" for t in rep["top_features"][:8]), ""]

    lines += [
        "## Limitations (read before relying on any number above)",
        "",
        "- **Lab traffic, not the internet.** Attacks are scripted by this repository and benign "
        "traffic is a handful of scripted HTTP/3 patterns. High scores show the pipeline works and "
        "that these generators are separable; they are not evidence about real-world QUIC traffic.",
        "- **Small corpus.** Intervals above are wide when the smallest class is under 30 flows.",
        "- **Evasion.** A model trained on clean traffic only is expected to be evaded by reshaped "
        "traffic; the `robust` profile narrows but does not remove that gap, and held-out variants "
        "estimate how much is left against evasion it has not seen.",
        "- **Novel attack types.** See \"Attack types the model never saw\": recall on an attack whose "
        "behaviour differs from the trained ones can fall to 0%. This is a supervised detector of "
        "known behaviours, not an anomaly detector; retrain when new attack classes appear.",
        "- **Not a replacement for payload inspection or host telemetry**; QUIC payloads are encrypted.",
        "- Model files are scikit-learn pickles: load only files you built yourself or trust.",
        "",
    ]
    return "\n".join(lines)
